import assert from "node:assert/strict";
import { mkdtemp, readFile, rm, writeFile, stat, symlink } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { makeScheduleReviewFixture } from "./schedule-review-fixture.js";
import { captureCli, commitWorkspaceFiles } from "./helpers.js";
import { runCli } from "../src/cli.js";
import { loadWorkspace } from "../src/workspace.js";
import { assessCollectionReview, scaffoldCollectionReview, planCollectionReview, applyCollectionReview } from "../src/collection-review.js";
import { getGitSummary } from "../src/git.js";
import { collectionReviewCommands } from "../src/collection-review-handoff.js";
import { validateWorkspace } from "../src/validate.js";
import { scheduleReviewPacket } from "../src/schedule-review-packet.js";

test("compact review explicitly reaffirms unchanged dispositions and saves the complete current set", async (context) => {
  const root = await mkdtemp(join(tmpdir(), "filegrc-review-packet-"));
  context.after(() => rm(root, { recursive: true, force: true }));
  const fixture = await makeScheduleReviewFixture(root);
  const domain = await scaffoldCollectionReview(root, { resourceType: "obligation", includeOperatingPreview: false });
  assert.deepEqual(domain.scheduleReview.counts, { total: 57, unchanged: 53, requiringDecision: 4 });
  assert.equal(domain.scheduleDecisions.length, 57, "legacy domain callers retain the complete array");
  assert.equal(domain.rationale, null);
  assert.deepEqual(domain.reviewedByIds, []);
  assert.equal(domain.reviewedOn, null);
  assert.equal(domain.confirmUnchangedSchedules, false);
  assert.equal(domain.firstOperatingTasks, undefined);
  const cli = JSON.parse((await captureCli(runCli, ["review-collection", "obligation", "--scaffold", "--root", root])).stdout);
  assert.equal(cli.scheduleDecisions.length, 4);
  assert.equal(cli.firstOperatingTasks, undefined);
  const initialAssessment = assessCollectionReview(await loadWorkspace(root), "obligation");
  const commands = collectionReviewCommands(initialAssessment);
  assert.ok(commands[0].includes("--output"));
  assert.ok(commands[1].includes("--preview --summary --json"));
  assert.ok(commands[2].includes("--yes --summary --json"));
  const draftPath = initialAssessment.reviewPayloadPath;
  context.after(() => rm(draftPath, { force: true }));
  await captureCli(runCli, ["review-collection", "obligation", "--root", root, "--scaffold", "--output", draftPath]);
  assert.equal(getGitSummary(root).clean, true, "following the handoff never dirties the reviewed checkout");
  assert.equal(JSON.parse(await readFile(draftPath, "utf8")).expectedCollectionRevision, cli.expectedCollectionRevision);
  if (process.platform !== "win32") assert.equal((await stat(draftPath)).mode & 0o777, 0o600);
  const editedDraft = { ...JSON.parse(await readFile(draftPath, "utf8")), rationale: "Preserve the reviewer's unfinished notes." };
  await writeFile(draftPath, JSON.stringify(editedDraft));
  await assert.rejects(captureCli(runCli, ["review-collection", "obligation", "--root", root, "--scaffold", "--output", draftPath]), /not overwritten/);
  assert.equal(JSON.parse(await readFile(draftPath, "utf8")).rationale, editedDraft.rationale);
  await assert.rejects(captureCli(runCli, ["review-collection", "obligation", "--root", root, "--scaffold", "--output", join(root, "REVIEW.json")]), /outside the checkout/);
  const alias = `${root}-alias`;
  await symlink(root, alias, process.platform === "win32" ? "junction" : "dir");
  context.after(() => rm(alias, { force: true, recursive: true }));
  await assert.rejects(captureCli(runCli, ["review-collection", "obligation", "--root", root, "--scaffold", "--output", join(alias, "REVIEW.json")]), /outside the checkout/);
  assert.ok(JSON.stringify(cli).length < 45_000, "a shared-source 57-schedule packet remains compact");
  const verbose = JSON.parse((await captureCli(runCli, ["review-collection", "obligation", "--scaffold", "--root", root, "--include-operating-preview"])).stdout);
  assert.ok(verbose.firstOperatingTasks);
  const changed = cli.scheduleReview.rows.filter(({ state }) => state !== "unchanged");
  const calendar = changed.find(({ current }) => current.nextWindow);
  assert.notEqual(calendar.previous.nextWindow.dueWindowEnd, calendar.current.nextWindow.dueWindowEnd);
  assert.equal(calendar.previous.timezone, "America/Chicago");
  assert.equal(calendar.current.timezone, "UTC");
  assert.equal(calendar.current.ruleConfiguration.cutoverDecision, "new-windows-only");
  const excluded = changed.find(({ obligationId }) => obligationId === "obligation-example");
  assert.equal(excluded.previous.otherRules.find(({ id }) => id === fixture.excludedId).status, "proposed");
  assert.equal(excluded.current.otherRules.find(({ id }) => id === fixture.excludedId).status, "withdrawn");
  const payload = { ...cli, confirmUnchangedSchedules: true, rationale: "Fresh review of all changed rules, timing effects and unchanged dispositions.",
    reviewedByIds: ["person-independent-approver-example"], reviewedOn: fixture.today,
    scheduleDecisions: cli.scheduleDecisions.map((row) => ({ ...row, disposition: "adopted", rationale: "Current governing requirement and allowed work reviewed.",
      ...(row.obligationId === "obligation-example" ? { excludedRuleIds: [fixture.excludedId] } : {}) })) };
  await assert.rejects(planCollectionReview(root, { ...payload, confirmUnchangedSchedules: false }), (error) => /every linked Obligation/.test(error.message)
    && /confirmUnchangedSchedules.*expectedPriorReviewRevision.*expectedCollectionRevision/.test(error.message));
  await assert.rejects(planCollectionReview(root, { ...payload, expectedPriorReviewRevision: undefined }), /prior schedule review changed/);
  await assert.rejects(planCollectionReview(root, { ...payload, expectedPriorReviewRevision: "stale" }), /prior schedule review changed/);
  await assert.rejects(planCollectionReview(root, { ...payload, reviewedByIds: ["person-example"] }), /independent/);
  const tampered = { ...payload, scheduleReview: { ...payload.scheduleReview, rows: payload.scheduleReview.rows.map((row) => ({ ...row, state: "unchanged", priorDecision: { disposition: "retired" } })) } };
  await assert.rejects(planCollectionReview(root, { ...tampered, scheduleDecisions: tampered.scheduleDecisions.slice(1) }), /every linked Obligation/);
  await writeFile(draftPath, JSON.stringify(payload));
  const previewSummaryText = (await captureCli(runCli, ["review-collection", "obligation", draftPath, "--root", root, "--preview", "--summary", "--json"])).stdout;
  const previewSummary = JSON.parse(previewSummaryText);
  assert.equal(previewSummary.status, "preview");
  assert.deepEqual(previewSummary.decisionCounts, { total: 57, unchanged: 53, requiringDecision: 4, reaffirmed: 53, explicit: 4 });
  assert.deepEqual(previewSummary.governedContentChanges, []);
  assert.equal(previewSummary.assessment, undefined);
  assert.ok(previewSummaryText.length < 5000, "normal preview does not repeat the full population and prior narratives");
  const plan = await planCollectionReview(root, { ...tampered, includeOperatingPreview: false });
  assert.ok(plan.changes.create[0].scheduleDecisions.every(({ disposition }) => disposition === "adopted"), "client context cannot change server-derived decisions");
  const legacy = { ...payload, confirmUnchangedSchedules: undefined, expectedPriorReviewRevision: undefined,
    scheduleDecisions: domain.scheduleDecisions.map((row) => ({ ...row, disposition: "adopted", rationale: "Explicit complete-array decision.", ...(row.obligationId === "obligation-example" ? { excludedRuleIds: [fixture.excludedId] } : {}) })) };
  assert.equal((await planCollectionReview(root, legacy)).changes.create[0].scheduleDecisions.length, 57);
  const fullExplicit = await planCollectionReview(root, { ...legacy, confirmUnchangedSchedules: true, expectedPriorReviewRevision: payload.expectedPriorReviewRevision });
  assert.equal(fullExplicit.reviewSummary.decisionCounts.explicit, 57);
  assert.equal(fullExplicit.reviewSummary.decisionCounts.reaffirmed, 0);
  const oneUnchanged = cli.scheduleReview.rows.find(({ state }) => state === "unchanged");
  const partialExplicit = await planCollectionReview(root, { ...payload, scheduleDecisions: [...payload.scheduleDecisions,
    { obligationId: oneUnchanged.obligationId, ruleId: oneUnchanged.current.ruleId, disposition: "adopted", rationale: "Explicit fresh decision for this unchanged row." }] });
  assert.equal(partialExplicit.reviewSummary.decisionCounts.explicit, 5);
  assert.equal(partialExplicit.reviewSummary.decisionCounts.reaffirmed, 52);
  assert.equal(plan.changes.create[0].scheduleDecisions.length, 57);
  assert.equal(plan.firstOperatingTasks, undefined);
  assert.ok(plan.changes.create[0].scheduleDecisions.filter(({ obligationId }) => !changed.some((row) => row.obligationId === obligationId))
    .every(({ rationale }) => rationale.startsWith("Explicitly reaffirmed") && !rationale.includes("Historical disposition")));
  // Another reviewer can change the prior-review record without changing the schedule collection.
  let loaded = await loadWorkspace(root);
  const priorEntry = loaded.entries.find(({ record }) => record.id === cli.scheduleReview.priorReview.id);
  const priorBytes = await readFile(priorEntry.path, "utf8");
  await writeFile(priorEntry.path, priorBytes.replace("Historical review", "Another historical review"));
  await assert.rejects(planCollectionReview(root, payload), /prior schedule review changed/);
  await assert.rejects(applyCollectionReview(root, { ...payload, confirmed: true }), /prior schedule review changed/);
  await writeFile(priorEntry.path, JSON.stringify({ ...priorEntry.record, scopeRevision: "0".repeat(40) }));
  const missingHistory = await scaffoldCollectionReview(root, { resourceType: "obligation", includeOperatingPreview: false });
  assert.equal(missingHistory.scheduleReview.historyAvailable, false);
  await assert.rejects(planCollectionReview(root, { ...payload, expectedPriorReviewRevision: missingHistory.expectedPriorReviewRevision }), /snapshot is unavailable/);
  await assert.rejects(applyCollectionReview(root, { ...payload, expectedPriorReviewRevision: missingHistory.expectedPriorReviewRevision, confirmed: true }), /snapshot is unavailable/);
  await writeFile(priorEntry.path, priorBytes);
  // Changed source proof requirements remain visible and cannot use old confirmations.
  const rule = loaded.entries.find(({ record }) => record.id === calendar.current.ruleId);
  const ruleBytes = await readFile(rule.path, "utf8");
  await writeFile(rule.path, JSON.stringify({ ...rule.record, completionCoverage: "whole-period" }));
  const edited = await scaffoldCollectionReview(root, { resourceType: "obligation", includeOperatingPreview: false });
  assert.equal(edited.scheduleReview.rows.find(({ obligationId }) => obligationId === calendar.obligationId).current.ruleConfiguration.completionCoverage, "whole-period");
  assert.ok(edited.changesSinceReview.changes.some((change) => change.id === calendar.current.ruleId && change.kind === "added"));
  await assert.rejects(planCollectionReview(root, payload), /changed after it was displayed/);
  await assert.rejects(applyCollectionReview(root, { ...payload, confirmed: true }), /changed after it was displayed/);
  await writeFile(rule.path, ruleBytes);
  const noHistory = scheduleReviewPacket({ ...loaded, root: null }, loaded.resources.find(({ type }) => type === "program"), priorEntry.record, cli.expectedPriorReviewRevision);
  assert.equal(noHistory.historyAvailable, false);
  assert.equal(noHistory.counts.unchanged, 0);
  const appliedSummary = JSON.parse((await captureCli(runCli, ["review-collection", "obligation", draftPath, "--root", root, "--yes", "--summary", "--json"])).stdout);
  assert.equal(appliedSummary.status, "recorded");
  assert.equal(appliedSummary.collectionReviewCurrent, true);
  assert.equal(appliedSummary.decisionCounts.reaffirmed, 53);
  assert.deepEqual(appliedSummary.retiredReviewIds, [priorEntry.record.id]);
  assert.deepEqual(appliedSummary.governedContentChanges, []);
  assert.ok(JSON.stringify(appliedSummary).length < 5000);
  loaded = await loadWorkspace(root);
  const assessment = assessCollectionReview(loaded, "obligation");
  assert.equal(assessment.complete, true);
  assert.equal(assessment.review.scheduleDecisions.length, 57);
  assert.equal(loaded.resources.find(({ id }) => id === priorEntry.record.id).status, "retired");
  assert.equal(loaded.resources.find(({ id }) => id === priorEntry.record.id).rationale, priorEntry.record.rationale);
  assert.equal(JSON.stringify(loaded.resources.filter(({ type }) => ["policy", "document", "training"].includes(type))), fixture.activationFacts);
  assert.equal((await validateWorkspace(root)).counts.errors, 0);
  await commitWorkspaceFiles(root, "Record the independently reaffirmed current schedule set");
  assert.equal(assessCollectionReview(await loadWorkspace(root), "obligation").complete, true);
});
